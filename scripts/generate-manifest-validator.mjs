import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
const schemaBytes = (await readFile(new URL('../schemas/jump-manifest.schema.json', import.meta.url), 'utf8')).replace(/\r\n/g, '\n');
const ajv = new Ajv2020({ strict: true, allErrors: true, code: { source: true, esm: true } });
let code = standaloneCode(ajv, ajv.compile(JSON.parse(schemaBytes)));
const runtime = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g;
code = code.replace(runtime, 'unicodeLength');
if (/require\s*\(|eval\s*\(|new Function\s*\(/.test(code)) throw new Error('Generated validator includes unsupported dynamic runtime');
const header = `// Generated by scripts/generate-manifest-validator.mjs; do not edit.\n// canonical-schema-sha256: ${createHash('sha256').update(schemaBytes).digest('hex')}\n`;
const helper = 'const unicodeLength = value => [...value].length;\n';
const output = header + helper + code + '\n';
const target = new URL('../src/manifest-validator.generated.mjs', import.meta.url);
if (process.argv.includes('--check')) {
 if (await readFile(target, 'utf8') !== output) throw new Error('Generated manifest validator is stale');
} else await writeFile(target, output);
